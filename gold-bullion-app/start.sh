if ! command -v python3 &> /dev/null; then
    echo "[خطا] python3 یافت نشد. لطفا پایتون را نصب کنید."
    exit 1
fi

echo "[1/2] در حال نصب بسته‌های پایتون..."
pip3 install -r requirements.txt --quiet

echo "[2/2] راه‌اندازی سرور روی http://0.0.0.0:8000 ..."
python3 app.py
